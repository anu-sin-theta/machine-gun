#!/usr/bin/env node
// Builds rust/kavach-wasm to WebAssembly and writes the generated glue plus an
// inlined base64 copy of the binary to src/rust/pkg.
//
// The output is committed: Vercel's build has no Rust toolchain, and inlining
// the binary means it loads the same way under Node, Next.js and Vitest with
// no filesystem lookups or output-file-tracing config.
//
//   pnpm build:wasm          build and write src/rust/pkg
//   pnpm build:wasm --check  build and fail if src/rust/pkg is out of date (CI)

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const rustDir = join(root, "rust");
const outDir = join(root, "src", "rust", "pkg");
const check = process.argv.includes("--check");

const env = { ...process.env };
const cargoBin = join(homedir(), ".cargo", "bin");
if (!env.PATH?.split(":").includes(cargoBin))
  env.PATH = `${cargoBin}:${env.PATH}`;

// Reproducible output: rustc embeds absolute source paths (panic locations,
// debug info). Remap them so the binary is identical on every machine, which
// is what lets `--check` compare against the committed copy in CI.
const cargoHome = process.env.CARGO_HOME ?? join(homedir(), ".cargo");
const rustHome = process.env.RUSTUP_HOME ?? join(homedir(), ".rustup");
env.RUSTFLAGS = [
  env.RUSTFLAGS,
  `--remap-path-prefix=${rustDir}=/kavach/rust`,
  `--remap-path-prefix=${cargoHome}=/cargo`,
  `--remap-path-prefix=${rustHome}=/rustup`,
]
  .filter(Boolean)
  .join(" ");

function run(cmd, args, cwd) {
  console.log(`$ ${cmd} ${args.join(" ")}`);
  execFileSync(cmd, args, { cwd, env, stdio: "inherit" });
}

const wasmIn = join(
  rustDir,
  "target",
  "wasm32-unknown-unknown",
  "release",
  "kavach_wasm.wasm",
);
const tmp = join(root, "node_modules", ".cache", "kavach-wasm");
rmSync(tmp, { recursive: true, force: true });
mkdirSync(tmp, { recursive: true });

run(
  "cargo",
  [
    "build",
    "-p",
    "kavach-wasm",
    "--release",
    "--target",
    "wasm32-unknown-unknown",
    "--locked",
  ],
  rustDir,
);
run(
  "wasm-bindgen",
  ["--target", "web", "--typescript", "--out-dir", tmp, wasmIn],
  rustDir,
);

const wasm = readFileSync(join(tmp, "kavach_wasm_bg.wasm"));
// The async init path references the .wasm by URL, which bundlers would try to
// resolve as an asset. We only ever use initSync with the inlined bytes, so
// replace that path with an explicit error. Fail the build if the glue changes.
const URL_LINE =
  "module_or_path = new URL('kavach_wasm_bg.wasm', import.meta.url);";
const rawGlue = readFileSync(join(tmp, "kavach_wasm.js"), "utf8");
if (!rawGlue.includes(URL_LINE)) {
  throw new Error(
    "wasm-bindgen glue changed: update URL_LINE in scripts/build-wasm.mjs",
  );
}
const glue = rawGlue.replace(
  URL_LINE,
  'throw new Error("kavach-wasm: async init is disabled; use initSync with the inlined bytes");',
);
const dts = readFileSync(join(tmp, "kavach_wasm.d.ts"), "utf8");
const banner =
  "// GENERATED by scripts/build-wasm.mjs from rust/kavach-wasm. Do not edit.\n";

const files = {
  "kavach_wasm.js": banner + glue,
  "kavach_wasm.d.ts": banner + dts,
  "kavach_wasm_bytes.ts":
    `${banner}// sha256(wasm) = ${createHash("sha256").update(wasm).digest("hex")}\n` +
    `export const WASM_BASE64 = "${wasm.toString("base64")}";\n`,
};

if (check) {
  const stale = Object.entries(files).filter(([name, content]) => {
    const path = join(outDir, name);
    return !existsSync(path) || readFileSync(path, "utf8") !== content;
  });
  if (stale.length > 0) {
    console.error(
      `src/rust/pkg is out of date: ${stale.map(([n]) => n).join(", ")}. Run: pnpm build:wasm`,
    );
    process.exit(1);
  }
  console.log("src/rust/pkg is up to date.");
} else {
  mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(files))
    writeFileSync(join(outDir, name), content);
  console.log(
    `wrote ${Object.keys(files).length} files to src/rust/pkg (wasm ${wasm.length} bytes)`,
  );
}
